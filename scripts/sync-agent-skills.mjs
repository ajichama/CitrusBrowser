#!/usr/bin/env node
/**
 * 共通スキルの正本（.agents/skills/<name>/SKILL.md。Codex・Antigravity が読む）から、
 * Claude Code が読む .claude/skills/<name>/SKILL.md を生成する。
 * 正本の frontmatter と本文をそのまま写す。以前は「正本を Read せよ」という案内だけを置いていたが、
 * スキルを使うたびに Read の往復が1回増え、そのたびに文脈全体を送り直していたため改めた。
 * 編集は正本だけで行い、--check でずれを検出する。付属ファイル（scripts/ 等）は写さない。
 * 本文はリポジトリのルートからの相対パスで正本の場所を指すので、写した先でもそのまま使える。
 * シンボリックリンクは Windows（権限）と Dropbox（同期）の両方で問題を起こしやすいため使わない。
 *
 *   node scripts/sync-agent-skills.mjs          # 生成・更新・不要分の削除
 *   node scripts/sync-agent-skills.mjs --check  # ずれがあれば終了コード1（CI・コミット前の確認用）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDir = path.join(root, '.agents', 'skills');
const targetDir = path.join(root, '.claude', 'skills');
const MARKER = '<!-- generated by scripts/sync-agent-skills.mjs: 編集は .agents/skills の正本で行う -->';
const check = process.argv.includes('--check');

/** 正本を読み、改行を LF にそろえて frontmatter と本文に分ける。 */
function readSkill(file) {
  const text = fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---\n/.exec(text);
  if (!match) throw new Error(`frontmatter がありません: ${file}`);
  const lines = match[1].split('\n');
  const name = lines.find((l) => l.startsWith('name:'))?.slice(5).trim();
  if (!name || !lines.some((l) => l.startsWith('description:'))) {
    throw new Error(`name / description がありません: ${file}`);
  }
  if (!/^[a-z0-9-]+$/.test(name)) throw new Error(`name は英小文字・数字・ハイフンのみ: ${name}`);
  return { name, frontmatter: match[0], body: text.slice(match[0].length) };
}

function render({ name, frontmatter, body }) {
  const note = `<!-- 正本: .agents/skills/${name}/SKILL.md（Codex・Antigravity と共有）。付属ファイルも正本の場所から使う -->`;
  return `${frontmatter}\n${MARKER}\n${note}\n${body.replace(/^\n+/, '\n')}`;
}

const expected = new Map();
for (const entry of fs.readdirSync(sourceDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(sourceDir, entry.name, 'SKILL.md');
  if (!fs.existsSync(file)) continue;
  const skill = readSkill(file);
  if (skill.name !== entry.name) throw new Error(`ディレクトリ名と name が一致しません: ${entry.name} / ${skill.name}`);
  expected.set(skill.name, render(skill));
}

const problems = [];
for (const [name, content] of expected) {
  const file = path.join(targetDir, name, 'SKILL.md');
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (current === content) continue;
  if (current !== null && !current.includes(MARKER)) {
    problems.push(`${name}: 手書きの .claude/skills があるため上書きしません`);
    continue;
  }
  if (check) { problems.push(`${name}: 生成内容と異なります（node scripts/sync-agent-skills.mjs を実行）`); continue; }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content, 'utf8');
  console.log(`更新: .claude/skills/${name}/SKILL.md`);
}
if (fs.existsSync(targetDir)) {
  for (const entry of fs.readdirSync(targetDir, { withFileTypes: true })) {
    const file = path.join(targetDir, entry.name, 'SKILL.md');
    if (!entry.isDirectory() || expected.has(entry.name) || !fs.existsSync(file)) continue;
    if (!fs.readFileSync(file, 'utf8').includes(MARKER)) continue; // 手書きの Claude 専用スキルは残す
    if (check) { problems.push(`${entry.name}: 正本が無い生成ファイルが残っています`); continue; }
    fs.rmSync(path.join(targetDir, entry.name), { recursive: true });
    console.log(`削除: .claude/skills/${entry.name}`);
  }
}

if (problems.length) {
  problems.forEach((p) => console.error(p));
  process.exitCode = 1;
} else {
  console.log(`同期済み: ${expected.size} 件`);
}
